// Checks what ESLint cannot: filler words and emoji in docs and comments, banned file
// names, broken relative links in docs, and the task tracker format.
// See docs/rules/writing.md and docs/tasks.md.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const skippedDirectories = new Set(['node_modules', '.git', 'dist', '.next', 'coverage', '.turbo']);
// writing.md lists the banned phrases on purpose.
const filesAllowedToNameFiller = new Set(['docs/rules/writing.md', 'scripts/check-docs.mjs']);

const fillerPhrases = [
  'delve',
  'leverage',
  'utilize',
  'facilitate',
  'seamless',
  'robust',
  'powerful',
  'cutting-edge',
  'state-of-the-art',
  'best-in-class',
  'comprehensive',
  'holistic',
  'end-to-end solution',
  'game-changer',
  'empower',
  'elevate',
  'streamline',
  "it's important to note",
  'it is important to note',
  'it is worth noting',
  'note that',
  'this ensures that',
  'in order to',
  "in today's",
  "let's dive",
  'dive into',
  'in conclusion',
  'navigate the complexities',
  'generated by',
  'as an ai',
  'i hope this helps',
];
const fillerPattern = new RegExp(`\\b(${fillerPhrases.join('|')})`, 'i');
// Pictographs and dingbats; leaves arrows, currency signs and Bangla text alone.
const emojiPattern = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}]/u;
const bannedFileNamePattern =
  /(^|[-.])(utils?|helpers?|managers?|misc|stuff|temp|tmp|enhanced)([-.]|$)/i;
const taskStatuses = new Set(['Todo', 'In progress', 'In review', 'Done', 'Blocked']);

const problems = [];
const report = (file, line, message) => problems.push(`${file}:${line}  ${message}`);

function listFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (skippedDirectories.has(entry.name)) return [];
    const path = join(directory, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  });
}

function commentText(line) {
  const trimmed = line.trim();
  if (trimmed.startsWith('//') || trimmed.startsWith('*') || trimmed.startsWith('/*')) {
    return trimmed;
  }
  const inlineComment = line.indexOf(' // ');
  return inlineComment === -1 ? '' : line.slice(inlineComment);
}

function checkWording(file, lines, textOf) {
  if (filesAllowedToNameFiller.has(file)) return;
  lines.forEach((line, index) => {
    const text = textOf(line);
    const filler = text.match(fillerPattern);
    if (filler) report(file, index + 1, `filler "${filler[1]}"; see docs/rules/writing.md`);
    if (emojiPattern.test(text)) report(file, index + 1, 'emoji; see docs/rules/writing.md');
  });
}

function checkLinks(file, lines) {
  const linkPattern = /\]\(([^)\s]+)\)/g;
  lines.forEach((line, index) => {
    for (const [, target] of line.matchAll(linkPattern)) {
      if (/^(https?:|mailto:|#)/.test(target)) continue;
      const path = target.split('#')[0];
      if (!existsSync(resolve(root, dirname(file), path))) {
        report(file, index + 1, `broken link ${target}`);
      }
    }
  });
}

function checkFileName(file) {
  const isSourceFile = /^(apps|packages)\/[^/]+\/src\//.test(file);
  if (!isSourceFile) return;
  const name = basename(file);
  if (bannedFileNamePattern.test(name)) {
    report(file, 1, 'name the file for what it holds; see docs/rules/naming-and-comments.md');
  }
  if (/^index\.tsx?$/.test(name)) {
    report(file, 1, 'no barrel files; see docs/rules/naming-and-comments.md');
  }
}

function tableCells(line) {
  return line
    .split('|')
    .slice(1, -1)
    .map((cell) => cell.trim());
}

function checkTaskTracker(file, lines) {
  const rows = lines
    .map((line, index) => ({ cells: tableCells(line), lineNumber: index + 1 }))
    .filter(({ cells }) => /^[A-Z]+-\d+$/.test(cells[0] ?? ''));
  const ids = new Set();
  for (const { cells, lineNumber } of rows) {
    const [id, , status] = cells;
    if (ids.has(id)) report(file, lineNumber, `duplicate task id ${id}`);
    ids.add(id);
    if (!taskStatuses.has(status)) {
      report(file, lineNumber, `status "${status}" is not one of ${[...taskStatuses].join(', ')}`);
    }
  }
  for (const { cells, lineNumber } of rows) {
    const dependencies = (cells[3] ?? '').split(',').map((value) => value.trim());
    for (const dependency of dependencies.filter(Boolean)) {
      if (!ids.has(dependency)) report(file, lineNumber, `unknown dependency ${dependency}`);
    }
  }
}

for (const path of listFiles(root)) {
  const file = relative(root, path);
  checkFileName(file);
  if (file.endsWith('.md')) {
    const lines = readFileSync(path, 'utf8').split('\n');
    checkWording(file, lines, (line) => line);
    checkLinks(file, lines);
    if (file === 'docs/tasks.md') checkTaskTracker(file, lines);
  } else if (/\.(ts|tsx|mjs|cjs)$/.test(file)) {
    const lines = readFileSync(path, 'utf8').split('\n');
    checkWording(file, lines, commentText);
  }
}

if (problems.length > 0) {
  console.error(problems.join('\n'));
  console.error(
    `\n${problems.length} problem(s). Fix them or, for a real exception, say why in the PR.`,
  );
  process.exit(1);
}
